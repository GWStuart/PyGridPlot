"""Generate the API reference (``docs/user/reference.md``) from the docstrings.

The reference lists everything ``import pygridplot`` provides, with
signatures, defaults and the documentation written in the code. Generating
it means it can never drift out of date: ``tests/test_docs.py`` fails when
the file differs from what this script would write. After changing a public
docstring or signature, run::

    python scripts/build_api_docs.py

Docstrings are Google style, with the Sphinx-style markup used in the code
(``:class:`~pygridplot.Plane```, double backticks). Both are converted to
Markdown here.
"""

from __future__ import annotations

import argparse
import dataclasses
import inspect
import os
import re
import sys
import textwrap
from collections.abc import Callable
from pathlib import Path
from typing import Any

os.environ.setdefault("PYGAME_HIDE_SUPPORT_PROMPT", "1")

import pygridplot as pgp

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "user" / "reference.md"

SECTIONS: list[tuple[str, str, list[str]]] = [
    (
        "The plane",
        "The object your program creates and calls every frame.",
        ["Plane", "show"],
    ),
    (
        "Derivatives",
        "Derivatives of any order of functions of one variable, exact for "
        "functions written with NumPy.",
        ["derivative", "derivatives"],
    ),
    (
        "Draggable points",
        "Points the user drags, created with `Plane.draggable`.",
        ["DraggablePoint"],
    ),
    (
        "Styles",
        "Reusable looks for plotted objects. Keyword arguments of the plotting "
        "methods override their fields.",
        ["LineStyle", "PointStyle", "PolygonStyle", "FillStyle", "ArrowStyle"],
    ),
    (
        "Themes",
        "The grid's appearance. Derive variations with `dataclasses.replace`.",
        ["GridTheme", "LIGHT", "DARK", "NumberFormat"],
    ),
    (
        "Configuration",
        "Settings for the controls, sampling and zoom limits.",
        [
            "InteractionConfig",
            "KeyBindings",
            "SamplingConfig",
            "CurveSampling",
            "ImplicitSampling",
            "ViewLimits",
            "CacheStats",
        ],
    ),
    (
        "The view",
        "The camera behind every plane (`plane.view`): centre, scale, axes and "
        "every coordinate conversion.",
        ["View", "ViewState"],
    ),
]

HEADER = """# API reference

<!-- Generated by scripts/build_api_docs.py from the docstrings: do not edit
by hand. Run `python scripts/build_api_docs.py` after changing the API. -->

Everything below is importable from the package (`import pygridplot as pgp`,
then `pgp.Plane`, `pgp.LineStyle`, ...). The [user guide](index.md) explains
how the pieces fit together; this page lists every class, function and
setting with its parameters and defaults.

"""

SECTION_NAMES = ("Args", "Attributes", "Returns", "Raises", "Note", "Example")


def main(argv: list[str] | None = None) -> None:
    """Write (or with ``--check``, compare) the reference."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if out of date")
    args = parser.parse_args(argv)
    text = build()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            sys.exit(f"{OUTPUT} is out of date: run python scripts/build_api_docs.py")
        return
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")


def build() -> str:
    """Return the whole reference as Markdown."""
    missing = (
        set(pgp.__all__)
        - {"__version__"}
        - {n for _, _, names in SECTIONS for n in names}
    )
    if missing:
        msg = f"public names missing from SECTIONS: {sorted(missing)}"
        raise RuntimeError(msg)
    parts = [HEADER, contents()]
    for title, intro, names in SECTIONS:
        parts.append(f"## {title}\n\n{intro}\n\n")
        for name in names:
            parts.append(document(name, getattr(pgp, name)))
    return "".join(parts).rstrip() + "\n"


def contents() -> str:
    """Return a table of contents with a link per public name."""
    lines = ["**Contents:**\n"]
    for title, _, names in SECTIONS:
        links = ", ".join(f"[`{name}`](#{anchor(name)})" for name in names)
        lines.append(f"- {title}: {links}")
    return "\n".join(lines) + "\n\n"


def anchor(name: str) -> str:
    """Return the Markdown anchor of a name's heading."""
    return name.lower()


def document(name: str, obj: object) -> str:
    """Document one public name."""
    if inspect.isclass(obj):
        return document_class(name, obj)
    if inspect.isfunction(obj):
        return f"### {name}\n\n{signature_block(name, obj)}\n{markdown(obj.__doc__)}\n"
    return document_constant(name, obj)


def document_constant(name: str, value: object) -> str:
    """Document a module-level constant (the theme presets)."""
    kind = type(value).__name__
    notes = {
        "LIGHT": "The default theme: dark lines and labels on white.",
        "DARK": "A dark theme: light lines and labels on a near-black background, "
        "with a lighter palette.",
    }
    body = notes.get(name, "")
    if dataclasses.is_dataclass(value):
        default = type(value)()
        changed = [
            f"`{f.name}={getattr(value, f.name)!r}`"
            for f in dataclasses.fields(value)
            if getattr(value, f.name) != getattr(default, f.name)
        ]
        if changed:
            body += " It differs from the defaults in " + ", ".join(changed) + "."
    return f"### {name}\n\nA `{kind}` instance. {body}\n\n"


def document_class(name: str, cls: type) -> str:
    """Document a class: its constructor, then its public members."""
    parts = [
        f"### {name}\n\n",
        signature_block(name, cls),
        "\n",
        markdown(cls.__doc__),
        "\n",
    ]
    members = public_members(cls)
    if members:
        parts.append(f"#### Members of `{name}`\n\n")
        for member_name, member in members:
            parts.append(document_member(name, member_name, member))
    return "".join(parts)


def public_members(cls: type) -> list[tuple[str, Any]]:
    """Return a class' own public methods and properties, in source order."""
    members = []
    for member_name, member in vars(cls).items():
        if member_name.startswith("_"):
            continue
        if isinstance(
            member, (property, staticmethod, classmethod)
        ) or inspect.isfunction(member):
            members.append((member_name, member))
    if dataclasses.is_dataclass(cls):  # fields are documented as attributes
        fields = {f.name for f in dataclasses.fields(cls)}
        members = [(n, m) for n, m in members if n not in fields]
    return members


def document_member(owner: str, name: str, member: Any) -> str:
    """Document one method or property."""
    instance = owner[0].lower() + owner[1:]
    if isinstance(member, property):
        returns = member.fget.__annotations__.get("return", "") if member.fget else ""
        kind = "read and write" if member.fset is not None else "read only"
        head = f"- **`{instance}.{name}`** (`{returns}`, {kind})"
        body = markdown(member.__doc__, indent="  ")
        return f"{head}\n\n{body}\n" if body.strip() else f"{head}\n\n"
    func: Callable[..., Any] = (
        member.__func__ if isinstance(member, (staticmethod, classmethod)) else member
    )
    call = format_signature(
        f"{instance}.{name}", func, drop_self=not isinstance(member, staticmethod)
    )
    body = markdown(func.__doc__, indent="  ")
    code = textwrap.indent(f"```py\n{call}\n```", "  ")
    return f"- **`{instance}.{name}()`**\n\n{code}\n\n{body}\n"


def signature_block(name: str, obj: Callable[..., Any]) -> str:
    """Return the call signature of a class or function as a code block."""
    target = obj
    if inspect.isclass(obj) and not dataclasses.is_dataclass(obj):
        target = obj.__init__  # type: ignore[misc]
    call = format_signature(
        f"pgp.{name}", target, drop_self=inspect.isclass(obj) and target is not obj
    )
    return f"```py\n{call}\n```\n"


def format_signature(name: str, func: Callable[..., Any], *, drop_self: bool) -> str:
    """Format a call signature, one parameter per line when it is long."""
    signature = inspect.signature(func)
    params = list(signature.parameters.values())
    if drop_self and params and params[0].name in ("self", "cls"):
        params = params[1:]
    texts = []
    star_done = False
    for param in params:
        if param.kind is param.KEYWORD_ONLY and not star_done:
            texts.append("*")
            star_done = True
        if param.kind is param.VAR_POSITIONAL:
            star_done = True
        texts.append(format_parameter(param))
    returns = signature.return_annotation
    suffix = (
        ""
        if returns in (inspect.Signature.empty, "None") or inspect.isclass(func)
        else f" -> {clean_annotation(returns)}"
    )
    one_line = f"{name}({', '.join(texts)}){suffix}"
    if len(one_line) <= 88:
        return one_line
    inner = ",\n".join(f"    {text}" for text in texts)
    return f"{name}(\n{inner},\n){suffix}"


def format_parameter(param: inspect.Parameter) -> str:
    """Format one parameter with its annotation and default."""
    prefix = (
        "*"
        if param.kind is param.VAR_POSITIONAL
        else "**"
        if param.kind is param.VAR_KEYWORD
        else ""
    )
    text = prefix + param.name
    if param.annotation is not inspect.Parameter.empty:
        text += f": {clean_annotation(param.annotation)}"
    if param.default is not inspect.Parameter.empty:
        text += f" = {format_default(param.default)}"
    return text


def clean_annotation(annotation: object) -> str:
    """Return a readable annotation (they are strings under PEP 563)."""
    text = (
        annotation
        if isinstance(annotation, str)
        else getattr(annotation, "__name__", repr(annotation))
    )
    return re.sub(r"\bpygridplot\.[\w.]+\.", "", str(text))


def format_default(value: object) -> str:
    """Return a readable default value."""
    if dataclasses.is_dataclass(value) and not isinstance(value, type):
        return f"{type(value).__name__}()"
    if isinstance(value, float) and value == round(value, 6):
        return repr(value)
    return repr(value)


def markdown(doc: str | None, indent: str = "") -> str:
    """Convert a Google-style docstring into Markdown."""
    if not doc:
        return ""
    text = inspect.cleandoc(doc)
    blocks = []
    lines = text.splitlines()
    i = 0
    paragraph: list[str] = []

    def flush() -> None:
        if paragraph:
            blocks.append(convert_markup(" ".join(line.strip() for line in paragraph)))
            paragraph.clear()

    while i < len(lines):
        line = lines[i]
        header = line.strip().rstrip(":")
        if (
            line.strip().endswith(":")
            and header in SECTION_NAMES
            and not line.startswith(" ")
        ):
            flush()
            body, i = indented_block(lines, i + 1)
            blocks.append(section(header, body))
            continue
        if not line.strip():
            flush()
        elif line.rstrip().endswith("::"):
            paragraph.append(line.rstrip()[:-1])
            flush()
            code, i = indented_block(lines, i + 1)
            blocks.append(
                "```py\n" + textwrap.dedent("\n".join(code)).strip() + "\n```"
            )
            continue
        elif line.lstrip().startswith(("* ", "- ")):
            flush()
            item, i = list_item(lines, i)
            blocks.append(item)
            continue
        else:
            paragraph.append(line)
        i += 1
    flush()
    body = "\n\n".join(block for block in blocks if block)
    return textwrap.indent(body, indent) + "\n"


def indented_block(lines: list[str], start: int) -> tuple[list[str], int]:
    """Collect the indented (or blank) lines following a header."""
    block = []
    i = start
    while i < len(lines) and (not lines[i].strip() or lines[i].startswith((" ", "\t"))):
        block.append(lines[i])
        i += 1
    while block and not block[-1].strip():
        block.pop()
    return block, i


def list_item(lines: list[str], start: int) -> tuple[str, int]:
    """Collect one bullet item (continuation lines are indented)."""
    first = lines[start].lstrip()[2:]
    parts = [first]
    i = start + 1
    while (
        i < len(lines)
        and lines[i].startswith("  ")
        and not lines[i].lstrip().startswith(("* ", "- "))
    ):
        parts.append(lines[i].strip())
        i += 1
    return "- " + convert_markup(" ".join(parts)), i


def section(name: str, body: list[str]) -> str:
    """Convert an Args/Attributes/Returns/Raises/Note section."""
    if name in ("Args", "Attributes", "Raises"):
        items = []
        for line in textwrap.dedent("\n".join(body)).splitlines():
            match = re.match(r"^(\*{0,2}[\w.]+)(?: \(([^)]*)\))?: (.*)$", line)
            if match and not line.startswith(" "):
                key, _type, rest = match.groups()
                items.append([f"`{key}`", rest])
            elif items:
                items[-1][1] += " " + line.strip()
        title = {"Args": "Parameters", "Attributes": "Attributes", "Raises": "Raises"}[
            name
        ]
        rendered = "\n".join(f"- {key}: {convert_markup(text)}" for key, text in items)
        return f"*{title}:*\n\n{rendered}"
    text = " ".join(line.strip() for line in body)
    label = {"Returns": "Returns", "Note": "Note", "Example": "Example"}[name]
    return f"*{label}:* {convert_markup(text)}"


def convert_markup(text: str) -> str:
    """Convert Sphinx-style roles and double backticks to Markdown."""
    text = re.sub(
        r":(?:class|func|meth|attr|mod|data|exc):`~?([^`]+)`",
        lambda m: f"`{short(m.group(1))}`",
        text,
    )
    return re.sub(r"``([^`]+)``", r"`\1`", text)


def short(target: str) -> str:
    """Shorten a dotted reference to its last component(s) for display."""
    target = target.removeprefix("pygridplot.")
    parts = target.split(".")
    if len(parts) > 2:
        return ".".join(parts[-2:]) if parts[-2][:1].isupper() else parts[-1]
    return target


if __name__ == "__main__":
    main()
